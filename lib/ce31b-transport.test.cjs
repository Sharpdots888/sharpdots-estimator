const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { createServiceCatalogEndpoint } = require('./service-catalog-endpoint');
const { createCatalogTransport, SOURCE_WORKSPACE } = require('./ce-catalog-transport');
const P = require('../services/ce-pricing');
const pair = JSON.parse(readFileSync(process.env.CE_PAIRED_FIXTURE || '/private/tmp/ce31-estimator-cost-handoff/paired-source.json', 'utf8'));
const config = { enabled: true, key: 'a'.repeat(64) };
const request = { method: 'GET', url: new URL('http://local.invalid/api/services/catalog'), session: { user: { id: 45 } }, contract: P.CONTRACT };
const response = body => new Response(JSON.stringify(body), { headers: { 'Content-Type': 'application/json' } });
test('paired negotiation retains exact authenticated scope and fails closed on fallback', async () => {
  let calls = 0, seen;
  const endpoint = createServiceCatalogEndpoint({ config, crmEnabled: true, authorizeActor: async u => u, fetchImpl: async (_, options) => { calls++; seen = options.headers; return response(pair); } });
  const result = await endpoint(request);
  assert.equal(result.status, 200); assert.equal(result.body.schema, P.CATALOG);
  assert.equal(seen['X-Estimator-Catalog-Contract'], P.CONTRACT); assert.equal(seen['X-Estimator-Actor-Id'], '45');
  for (const contract of ['', 'v2', [P.CONTRACT], `${P.CONTRACT}, ${P.CONTRACT}`, ` ${P.CONTRACT}`]) assert.equal((await endpoint({ ...request, contract })).status, 400);
  assert.equal(calls, 1);
  const fallback = createServiceCatalogEndpoint({ config, crmEnabled: true, authorizeActor: async u => u, fetchImpl: async () => response(pair.structure) });
  assert.equal((await fallback(request)).status, 502);
  assert.equal((await fallback({ ...request, contract: undefined })).body.schema, 'ce-estimator-catalog-v1');
});
test('paired source uses total response bound and existing authorization', async () => {
  const read = createCatalogTransport({ config, maxBytes: 1000, fetchImpl: async () => response(pair) });
  await assert.rejects(read({ actor: { id: 45 }, workspace: SOURCE_WORKSPACE, contract: P.CONTRACT }), /size/);
  let calls = 0;
  const endpoint = createServiceCatalogEndpoint({ config, crmEnabled: true, authorizeActor: async () => { throw Object.assign(Error('denied'), { statusCode: 403 }); }, fetchImpl: async () => { calls++; return response(pair); } });
  assert.equal((await endpoint(request)).status, 403);
  assert.equal((await endpoint({ ...request, session: null })).status, 401); assert.equal(calls, 0);
});
