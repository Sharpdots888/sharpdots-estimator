const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/private/tmp/sharpdots-migration-tools/node_modules/playwright');
const assert = require('node:assert/strict');
const P = require('./ce-pricing');
const url = process.env.SERVICES_PREVIEW_URL || 'http://127.0.0.1:4213/index.html?crm=1&cePreview=1';
if (!['localhost', '127.0.0.1'].includes(new URL(url).hostname)) throw Error('Local preview only');
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
    await page.goto(url);
    await page.locator('[data-action=nav][data-page=proposals]').click();
    await page.locator('#crmOpportunity').selectOption({ index: 1 });
    await page.evaluate(() => newWorkspaceRecord('services'));
    await page.locator('[data-service-action=catalog]').first().click();
    await page.locator('.eng-dialog [data-service-action=ce-add][data-id=sm-pipeline]').click();
    await page.locator('.eng-dialog footer [data-service-action=close]').click();
    const total = () => page.evaluate(() => ServiceEngagement.totals(serviceEngagement));
    assert.equal((await total()).termPrice, 37375);
    await page.locator('[data-service-action=ce-view][data-view=components]').click();
    await page.locator('[data-service-action=ce-component]').first().click();
    await page.locator('#ceComponentForm [name=unitCost]').fill('380.125');
    await page.locator('#ceComponentForm [name=sellRate]').fill('650');
    await page.locator('#ceComponentForm [name=reason]').fill('Fictional estimate rate adjustment');
    await page.locator('#ceComponentForm [type=submit]').click();
    assert.equal((await total()).adjustedFromProduct, true);
    assert.match(await page.locator('#serviceEngagementBuilder').innerText(), /Adjusted from product/);
    await page.locator('[data-service-action=ce-view][data-view=products]').click();
    await page.locator('[data-service-action=ce-pricing]').click();
    await page.locator('#cePricingForm [name=markup]').fill('50');
    await page.locator('#cePricingForm [name=reason]').fill('Fictional estimate markup adjustment');
    await page.locator('#cePricingForm [type=submit]').click();
    await page.locator('#servicesView [data-record-action=save]').click();
    await page.locator('[data-service-action=proposal]').click();
    const savedS = await page.evaluate(() => structuredClone(savedRecordForCollection('services')));
    await page.evaluate(() => saveRecordFromManager('proposals'));
    const savedP = await page.evaluate(() => structuredClone(savedRecordForCollection('proposals')));
    await page.locator('#proposal-content-tab').click();
    await page.locator('[data-service-action=proposal-pricing]').click();
    const shell = page.locator('.ce-proposal-dialog');
    await shell.locator('[data-service-action=ce-pricing]').click();
    await page.locator('#cePricingForm [name=markup]').fill('80');
    await page.locator('#cePricingForm [name=reason]').fill('Fictional proposal-only markup');
    await page.locator('#cePricingForm [type=submit]').click();
    await shell.locator('[data-service-action=ce-view][data-view=components]').click();
    await shell.locator('[data-service-action=ce-component]').nth(1).click();
    await page.locator('#ceComponentForm [name=unitCost]').fill('285.125');
    await page.locator('#ceComponentForm [name=sellRate]').fill('600');
    await page.locator('#ceComponentForm [name=reason]').fill('Fictional proposal-only rate');
    await page.locator('#ceComponentForm [type=submit]').click();
    await shell.locator('[data-save-pricing]').click();
    await shell.waitFor({ state: 'hidden' });
    const overrideP = await page.evaluate(() => structuredClone(savedRecordForCollection('proposals')));
    assert.equal(overrideP.version, savedP.version + 1);
    assert.equal(P.digest(await page.evaluate(() => savedRecordForCollection('services'))), P.digest(savedS));
    assert.ok(overrideP.snapshot.proposal.servicesPricingOverride);
    assert.equal(P.digest(overrideP.versions.find(v => v.version === savedP.version).snapshot), P.digest(savedP.snapshot));
    const expected = P.calculate(overrideP.snapshot.proposal.servicesPricingOverride.configuration);
    assert.equal(await page.evaluate(() => proposalServiceTotals().termPrice), expected.termPrice);
    await page.evaluate(v => applyWorkspaceRecord('proposals', savedRecordForCollection('proposals'), v), savedP.version);
    assert.equal(await page.evaluate(() => proposal.servicesPricingOverride), undefined);
    await page.evaluate(v => applyWorkspaceRecord('proposals', savedRecordForCollection('proposals'), v), overrideP.version);
    assert.equal(await page.evaluate(() => proposalServiceTotals().termPrice), expected.termPrice);
    await page.evaluate(() => {
      window.ce31bOriginalState = structuredClone(serviceEngagement);
      serviceEngagement = ServiceEngagement.empty(); serviceScenario = 'scratch'; renderProposal();
    });
    assert.equal(await page.evaluate(() => proposalServiceTotals().termPrice), expected.termPrice);
    assert.equal(await page.evaluate(() => proposalSnapshotWithSources().sourceRecords.services.version), savedS.version);
    await page.evaluate(() => { proposal.outputAudience = 'client'; renderProposal(); });
    for (const id of ['proposalPublishPdfBtn', 'proposalPublishCsvBtn', 'proposalSignatureBtn']) assert.equal(await page.locator(`#${id}`).isDisabled(), true);
    assert.equal(await page.locator('#proposalServicesSection').isVisible(), false);
    assert.equal(await page.locator('.proposal-preview').getByText('Adjusted from product').count(), 0);
    await page.evaluate(() => { serviceEngagement = window.ce31bOriginalState; serviceScenario = 'livingOps'; proposal.outputAudience = 'internal'; renderProposal(); });
    for (const width of [1440, 1188, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.locator('[data-service-action=proposal-pricing]').click();
      await shell.locator('[data-service-action=ce-view][data-view=components]').click();
      const bounds = await shell.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await shell.screenshot({ path: `/private/tmp/ce31b-proposal-${width}.png` });
      await shell.locator('[data-service-action=close-shell]').click();
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('[data-service-action=proposal-pricing]').click();
    await shell.locator('[data-service-action=reset-proposal]').click();
    await shell.locator('[data-save-pricing]').click();
    await shell.waitFor({ state: 'hidden' });
    assert.equal(await page.evaluate(() => proposal.servicesPricingOverride), undefined);
    assert.equal(await page.evaluate(() => savedRecordForCollection('proposals').version), overrideP.version + 1);
    assert.equal(P.digest(await page.evaluate(() => savedRecordForCollection('services'))), P.digest(savedS));
    assert.deepEqual(errors, []);
    console.log('CE31B browser: paired catalog, estimate rates, proposal markup/rates/version/restore/reset, unchanged Services, client guards and 3 widths passed.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
