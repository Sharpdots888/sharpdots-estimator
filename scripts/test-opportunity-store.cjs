const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {randomUUID}=require('node:crypto');
const {PGlite}=require('@electric-sql/pglite');
const {createOpportunityStore}=require('../lib/opportunity-store');
const {createCrmAccess}=require('../lib/crm-access');
const M=require('../crm/model');

test('CRM persistence: identities, references, versions, acceptance and conflicts',async()=>{
  const db=new PGlite();
  const query=async(sql,values)=>{const r=await db.query(sql,values);return {...r,rowCount:r.rows.length||r.affectedRows||0};};
  const client={query,release(){}};
  const store=createOpportunityStore({...client,connect:async()=>client});
  const admin={id:45,isAdmin:true},company=randomUUID(),person=randomUUID();
  try{
    await db.exec(`CREATE ROLE db_admin;CREATE TABLE users(id integer PRIMARY KEY,username text,is_admin boolean,is_active boolean);
      INSERT INTO users VALUES(45,'test-admin',true,true),(46,'non-admin',false,true),(47,'disabled',true,false);
      CREATE TABLE sfvc_companies(company_id uuid PRIMARY KEY,legal_name text,company_type text);
      CREATE TABLE sfvc_people(person_id uuid PRIMARY KEY,first_name text,last_name text,email text);
      CREATE TABLE sfvc_company_people(company_id uuid,person_id uuid);`);
    for(const name of ['001_sfpq_opportunities.sql','002_opportunity_persistence.sql'])await db.exec(readFileSync(require('node:path').join(__dirname,'../migrations',name),'utf8'));
    await query('INSERT INTO sfvc_companies(company_id,legal_name) VALUES($1,$2)',[company,'Test company']);
    await query('INSERT INTO sfvc_people VALUES($1,$2,$3,$4)',[person,'Test','Contact','test@example.invalid']);
    await assert.rejects(store.list(null),e=>e.statusCode===401);
    await assert.rejects(store.list({id:46,isAdmin:true}),e=>e.statusCode===403);
    await assert.rejects(store.list({id:47,isAdmin:true}),e=>e.statusCode===403);
    await assert.rejects(store.createCompany({id:46,isAdmin:true},{name:'Blocked',creationKey:randomUUID()}),e=>e.statusCode===403);
    const companyInput={name:'New CRM Client',creationKey:randomUUID()};
    const createdCompany=await store.createCompany(admin,companyInput);
    assert.equal((await store.createCompany(admin,companyInput)).id,createdCompany.id);
    assert.equal((await query('SELECT company_type FROM sfvc_companies WHERE company_id=$1',[createdCompany.id])).rows[0].company_type,'customer');
    await assert.rejects(store.createCompany(admin,{name:' new crm client ',creationKey:randomUUID()}),e=>e.statusCode===409);
    const contactInput={companyId:createdCompany.id,firstName:'New',lastName:'Buyer',email:'BUYER@example.invalid',creationKey:randomUUID()};
    const createdContact=await store.createContact(admin,contactInput);
    assert.equal(createdContact.email,'buyer@example.invalid');
    assert.equal((await store.createContact(admin,contactInput)).id,createdContact.id);
    assert.equal((await query('SELECT 1 FROM sfvc_company_people WHERE company_id=$1 AND person_id=$2',[createdCompany.id,createdContact.id])).rowCount,1);
    await assert.rejects(store.createContact(admin,{...contactInput,creationKey:randomUUID()}),e=>e.statusCode===409);
    await assert.rejects(store.createContact(admin,{...contactInput,companyId:randomUUID(),creationKey:randomUUID()}),e=>e.statusCode===400);
    await assert.rejects(store.createContact(admin,{...contactInput,email:'invalid',creationKey:randomUUID()}),e=>e.statusCode===400);
    await assert.rejects(store.createContact(admin,{...contactInput,email:'',creationKey:randomUUID()}),e=>e.statusCode===409);
    await assert.rejects(store.createCompany(admin,null),e=>e.statusCode===400);
    const draft=M.make({title:'Durable opportunity',ownerId:45,owner:'test-admin',account:'Test company',contact:'Test Contact',oneTime:100,creationKey:randomUUID()});
    const a=await store.save(admin,null,draft);
    assert.equal(a.number,'O-000001');assert.equal(a.rowVersion,1);
    assert.equal((await store.save(admin,null,draft)).id,a.id);
    assert.equal((await store.list(admin)).opportunities.length,1);
    await assert.rejects(store.save(admin,a.id,{...a,accountRef:company,contactRef:person}),/does not belong/);
    await query('INSERT INTO sfvc_company_people VALUES($1,$2)',[company,person]);
    let b=await store.save(admin,a.id,{...a,accountRef:company,contactRef:person});
    await assert.rejects(store.save(admin,a.id,a),e=>e.statusCode===409);
    const record={collection:'proposals',name:'Offer',creationKey:randomUUID(),snapshot:{proposal:{title:'Offer'}}};
    const r=await store.saveRecord(admin,null,record);
    assert.match(r.number,/^P-\d{6}$/);
    assert.equal((await store.saveRecord(admin,null,record)).id,r.id);
    b=await store.save(admin,b.id,{...b,records:[{...r,role:'Primary offer'}]});
    await assert.rejects(store.save(admin,b.id,{...b,status:'won',stage:'won',documents:[{number:r.number,version:1,status:'completed',primary:true}]}),/approval reference/);
    b=await store.save(admin,b.id,{...b,approval:{method:'Purchase order',reference:'TEST-PO-1'}});
    b=await store.save(admin,b.id,{...b,status:'won',stage:'won'});
    assert.equal(b.status,'won');assert.equal(b.history[0].operator,'test-admin');
    await assert.rejects(store.save(admin,b.id,{...b,oneTime:200}),/Reopen/);
    b=await store.save(admin,b.id,{...b,status:'open',stage:'qualified'});
    assert.equal(b.billing.status,'not-ready');
    const next=await store.saveRecord(admin,r.id,{...record,version:1,snapshot:{proposal:{title:'New immutable offer'}}});
    assert.equal(next.version,2);
    await assert.rejects(store.saveRecord(admin,r.id,{...record,version:1}),e=>e.statusCode===409);
    const loaded=await store.list(admin);
    assert.equal(loaded.records.length,2);assert.equal(loaded.opportunities[0].records[0].version,1);
    assert.equal(loaded.records[0].snapshot.proposal.title,'Offer');
    b=await store.save(admin,b.id,{...b,records:[],note:'Detach for review'});
    assert.equal(b.records.length,0);assert.equal((await store.list(admin)).records.length,2);
    assert.equal(b.history[0].text,'Note: Detach for review');
    await db.exec(`CREATE TABLE sfpq_document_transactions(transaction_id uuid,proposal_number text,proposal_version integer,status text,recipient_email text,provider_submission_id text,updated_at timestamptz);`);
    b=await store.save(admin,b.id,{...b,records:[{...next,role:'Primary offer'}]});
    await query('INSERT INTO sfpq_document_transactions VALUES($1,$2,1,$3,$4,$5,now())',[randomUUID(),r.number,'completed','test@example.invalid','prior-version']);
    await assert.rejects(store.save(admin,b.id,{...b,status:'won',stage:'won'}),/approval reference/);
    await query('INSERT INTO sfpq_document_transactions VALUES($1,$2,2,$3,$4,$5,now())',[randomUUID(),r.number,'completed','test@example.invalid','current-version']);
    b=await store.save(admin,b.id,{...b,status:'won',stage:'won'});
    assert.equal(b.status,'won');
    const closedAt=b.closedAt;
    b=await store.save(admin,b.id,{...b,note:'Post-close note'});
    assert.deepEqual(b.closedAt,closedAt);
    await assert.rejects(store.save(admin,b.id,{...b,email:'different@example.invalid'}),/Reopen/);
    b=await store.save(admin,b.id,{...b,status:'open',stage:'qualified',oneTime:200});
    await assert.rejects(store.save(admin,b.id,{...b,status:'won',stage:'won'}),/approval reference/);
    assert.ok(b.documents.every(d=>d.superseded));
  }finally{await db.close();}
});

test('named CRM user can use shared records without administrator or document-send rights',async()=>{
  const db=new PGlite();
  const query=async(sql,values)=>{const r=await db.query(sql,values);return {...r,rowCount:r.rows.length||r.affectedRows||0};};
  const client={query,release(){}};
  const access=createCrmAccess('46');
  const store=createOpportunityStore({...client,connect:async()=>client},access);
  try{
    await db.exec(`CREATE ROLE db_admin;
      CREATE TABLE users(id integer PRIMARY KEY,username text,is_admin boolean,is_active boolean);
      INSERT INTO users VALUES(45,'admin',true,true),(46,'ray',false,true),(47,'other',false,true),(48,'disabled',false,false);
      CREATE TABLE sfvc_companies(company_id uuid PRIMARY KEY);
      CREATE TABLE sfvc_people(person_id uuid PRIMARY KEY);
      CREATE TABLE sfvc_company_people(company_id uuid,person_id uuid);`);
    for(const name of ['001_sfpq_opportunities.sql','002_opportunity_persistence.sql'])
      await db.exec(readFileSync(require('node:path').join(__dirname,'../migrations',name),'utf8'));
    const ray={id:46,isAdmin:false};
    assert.equal(access.allowsSession(ray),true);
    assert.equal(access.allowsSession({id:47,isAdmin:false}),false);
    assert.equal(access.allowsSession({id:45,isAdmin:true}),true);
    assert.equal(access.allowsSession(null),false);
    assert.deepEqual((await store.list(ray)).opportunities,[]);
    const input=M.make({title:'Ray pilot',ownerId:46,owner:'ray',creationKey:randomUUID()});
    const created=await store.save(ray,null,input);
    assert.equal(created.ownerId,46);
    const record=await store.saveRecord(ray,null,{collection:'estimates',name:'Ray estimate',snapshot:{rows:[]},creationKey:randomUUID()});
    assert.equal(record.collection,'estimates');
    assert.equal((await store.list(ray)).records.length,1);
    await assert.rejects(store.list({id:47,isAdmin:false}),e=>e.statusCode===403);
    await assert.rejects(store.saveRecord({id:47,isAdmin:false},null,{collection:'estimates',name:'No',snapshot:{},creationKey:randomUUID()}),e=>e.statusCode===403);
    await assert.rejects(store.list({id:48,isAdmin:false}),e=>e.statusCode===403);
    await assert.rejects(store.list({id:47,isAdmin:true}),e=>e.statusCode===403);
    assert.equal(require('../document-security').canSendClientDocuments({user:ray}),false);
  }finally{await db.close();}
});
